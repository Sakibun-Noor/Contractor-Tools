"""Builds m/m-hier.js, the parent/child links the portrait cascading lists need.

Reads (read-only):
  - the master database  CTD-product-db/out/CTD_Complete_Vendor_Product_Database_1_1381.xlsx
  - the Subcategory_ID -> final category slug table inside build/import-vendors.ps1
Writes:
  - m/m-hier.js  (portrait only; no landscape file or shared data file is touched)

Run:  python build/portrait-hierarchy.py
"""
import json, os, re, sys
import openpyxl

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
DB = os.path.join(os.path.expanduser('~'), 'Desktop', 'Claude', 'CTD-product-db', 'out',
                  'CTD_Complete_Vendor_Product_Database_1_1381.xlsx')
PS1 = os.path.join(ROOT, 'build', 'import-vendors.ps1')
OUT = os.path.join(ROOT, 'm', 'm-hier.js')
EN = '–'

def rows(wb, name):
    r = list(wb[name].iter_rows(values_only=True))
    h = r[0]
    return [dict(zip(h, x)) for x in r[1:] if any(c is not None for c in x)]

ps = open(PS1, encoding='utf-8').read()
block = ps[ps.index('$SUBCAT_TO_CAT_SLUG = @{'):]
block = block[:block.index('\n}')]
sub_slug = {int(a): b for a, b in re.findall(r"(\d+)\s*=\s*'([a-z\-]+)'", block)}

wb = openpyxl.load_workbook(DB, read_only=True, data_only=True)
subs = {int(r['Subcategory_ID']): r['Subcategory_Name'] for r in rows(wb, 'SUBCATEGORIES_NORM')}
missing = [i for i in subs if i not in sub_slug]
if missing:
    sys.exit('subcategories with no category slug: %s' % missing)
sub_cat = {subs[i]: sub_slug[i] for i in subs}

prod_name = {r['Vendor_Product_ID']: r['Product_Name'] for r in rows(wb, 'PRODUCTS_NORM')}
prod_subs = {}
for r in rows(wb, 'PRODUCT_SUBCATEGORY'):
    n = prod_name.get(r['Vendor_Product_ID'])
    s = subs.get(int(r['Subcategory_ID']))
    if n and s and s not in prod_subs.setdefault(n, []):
        prod_subs[n].append(s)

divs = {int(r['division_id']): r for r in rows(wb, 'DIVISIONS_NORM')}
def div_value(r):
    return '%s %s %s' % (r['CSI_Division_Number'], EN, r['division_name'])
div_mg = {div_value(r): r['master_group_name'] for r in divs.values() if r['CSI_Division_Number'] != 'ALL'}
trd_div = {}
for r in rows(wb, 'TRADES_NORM'):
    if r['CSI_Trade_Number'] == 'ALL':
        continue
    d = divs.get(int(r['division_id']))
    if d is None:
        continue
    trd_div['%s %s %s' % (r['CSI_Trade_Number'], EN, r['trade_name'])] = div_value(d)

out = {'subCat': sub_cat, 'prodSubs': prod_subs, 'divMg': div_mg, 'trdDiv': trd_div}
js = '/* Generated by build/portrait-hierarchy.py - do not edit by hand. */\nwindow.M_HIER = ' + \
     json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(OUT, 'w', encoding='utf-8', newline='\n').write(js)
print('subcategories %d | products with subs %d | divisions %d | trades %d | %d KB' %
      (len(sub_cat), len(prod_subs), len(div_mg), len(trd_div), len(js) // 1024))
